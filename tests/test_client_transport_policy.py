def test_a_command_split_over_a_continuation_is_still_one_command() -> None:
    """The evasion a per-line scan cannot see.

    Neither physical line carries a matchable token on its own; joined, the
    command is the forwarded-port recipe the gate exists to keep out. The
    offence is reported at the line the command starts on.
    """
    split = 'ssh -N \\\n  -L 8787:127.0.0.1:8787 <vps>\n'
    assert _offending_lines("docs/deployment.md", split) == [
        "docs/deployment.md:1: ssh -N -L 8787:127.0.0.1:8787 <vps>"
    ]
    # ...and the same text in the client surface, which has the stricter rule.
    assert _offending_lines("client/build.ps1", split)
    # A trailing continuation at end of file must not swallow the last line.
    assert _offending_lines("docs/deployment.md", "ssh -N -L 1:2:3 host \\")


