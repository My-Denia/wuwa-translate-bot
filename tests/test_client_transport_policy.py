"""Repository gate: the desktop client's transport design cannot regress
into a host-administration channel, and cannot stop verifying certificates.

The client reaches the service at a configured secure endpoint and
authenticates every request with a device credential. Host shell access is
the operator's administration channel; it is not how the application talks
to the service, and no shipped file may teach otherwise.

These are text gates, deliberately in the repository suite rather than the
client's own: they cover files from three different trees (client sources,
client tests, the client guide, the Compose file), and they must run on
every pull request without a Windows runner or the client's dependencies.
"""

from __future__ import annotations

import re
import shlex
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]

# (a) The scan scope is the UNION of the shipped client surface and the
#     deployment files that describe how it is reached.
#
# The client side is scanned by RECURSION over `client/`, not by a list: a
# list has to be maintained, and a file added to the client root tomorrow
# would be silently out of scope. Build artefacts and virtual environments
# are excluded because they are third-party bytes, not shipped surface.
#
# The owner-private web presentation layer is scanned by the same recursion,
# and for the same reason the client tree is. It is a THIRD surface reached
# over the network by a person, and the revoked design - "get to it by opening
# a tunnel to the host" - is exactly as available a wrong answer there as it
# was for the desktop client. Before this tree was listed here the whole
# package sat outside the scan, so the guard would have stayed green over
# anything written in it: that green would have been the absence of a check,
# not the absence of an offence.
#
# It lands under the STRICT rule automatically, because `_offending_lines`
# derives strictness as "not in RECIPE_ONLY_PATHS" - the default is strict and
# leniency is the thing that has to be asked for by name.
SCANNED_TREES = (
    ROOT / "client",
    ROOT / "src" / "wuwaterm_api" / "web",
)
EXCLUDED_DIR_NAMES = {
    ".venv",
    "venv",
    "build",
    "dist",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
}
# `pip install -e client[dev]` writes client/src/wuwaterm_client.egg-info/*.txt,
# and `.txt` is a scanned suffix - generated bytes that would be scanned as
# though they were authored.
EXCLUDED_DIR_SUFFIXES = (".egg-info",)
SCANNED_FILES = (
    # The runbook. tests/test_deploy_scripts.py pins four literal recipes in
    # it; this adds the pattern scan, so a spelling those literals miss
    # (`ssh -fNL`, `autossh`, prose) is caught as well.
    ROOT / "docs" / "deployment.md",
    # The web layer's operator guide. It is here for the same reason
    # deployment.md is: it tells a reader how the surface is reached, so it is
    # a place where "reach it by opening a tunnel" could be written down. It is
    # NOT in RECIPE_ONLY_PATHS, so it gets the strict rule - unlike the
    # deployment runbook it has no legitimate need to name the administration
    # channel at all.
    ROOT / "docs" / "web-presentation-layer.md",
    *sorted((ROOT / "deploy").glob("*.yml")),
    *sorted((ROOT / "deploy").glob("*.yaml")),
    # The deployment scripts. A helper that grew a forwarded port would
    # otherwise be the one place nothing looked - a shell script is where such
    # a thing naturally appears.
    *sorted((ROOT / "deploy").glob("*.sh")),
)
SCANNED_SUFFIXES = {".py", ".md", ".yml", ".yaml", ".spec", ".ps1", ".txt", ".toml"}

# Two rules, because the two surfaces have different jobs - but ONE source of
# truth for the forwarding half, so the strict rule is a superset of the
# lenient one by construction rather than by two lists staying in step.
#
# A forwarding instruction is written in one of two ways, and they need two
# different readers:
#
#   PROSE - "tunnel", "port-forward", "a forwarded port", `LocalForward` - is
#   matched anywhere on the line, because it means the same thing wherever it
#   appears, quoted or not.
#
#   A COMMAND is matched by PARSING it (`_ssh_option_flags`). Five rounds of
#   review went into learning that a regex cannot find where ssh's own
#   arguments end: the whole line made `ssh <vps> 'chmod -R 755 /opt'` an
#   offence; blanking quotes lost `ssh -L "8787:…"`; stopping at the first
#   quote lost `ssh -i "a key" -L 8787:…` and still rejected
#   `ssh <vps> curl -L https://…`. `ssh -h` states the structure in one line -
#   `ssh [options] destination [command [argument ...]]` - and reading the
#   option letters is both simpler and exact. Inside ssh's own options, `-L`,
#   `-R` and `-D` ARE forwarding whatever their argument looks like, so the
#   shape rules that used to be needed are gone with the guessing.
#
# The shapes below survive for one case only: a line with no `ssh` on it at
# all, where there is nothing to parse.
_SPEC_LR = r"(?=\s*\S*:)"
_SPEC_D = r"(?=\s*\S*\d)"

# Wording that is a forwarding instruction wherever it appears, quoted or not.
_RECIPE_PROSE_SOURCE = r"""
    \btunnel\w* | \bautossh\b
    | \bport[-\s]?forward\w*
    | \bLocalForward\b | \bRemoteForward\b | \bDynamicForward\b
    | \bforward\w*\s+(the\s+)?port\b | \bforwarded\s+port\b
"""

# Flag forms for a line with no `ssh` command on it to parse - a config-file
# fragment, a snippet quoted out of context.
_RECIPE_FLAG_SOURCE = rf"""
    (?-i:-N\s+-L)
    | \s-\w*(?-i:[LR]){_SPEC_LR}
    | \s-\w*(?-i:D){_SPEC_D}
"""

# The OPERATOR RUNBOOK legitimately names the administration channel - the
# deployment and credential commands are run over it - so only the forwarding
# half applies there. "Shell access is required to run these commands" must
# stay sayable; teaching a forwarded port must not.
RECIPE_PROSE = re.compile(_RECIPE_PROSE_SOURCE, re.IGNORECASE | re.VERBOSE)
RECIPE_FLAGS = re.compile(_RECIPE_FLAG_SOURCE, re.IGNORECASE | re.VERBOSE)

# The SHIPPED CLIENT SURFACE may not name the administration channel at all,
# outside the one allowlisted note: the client does not use it, and a mention
# there is how the revoked design comes back. Everything the runbook rule
# catches, this one catches too - it is the same two patterns plus the bare
# name.
CLIENT_SURFACE_ONLY = re.compile(r"\bssh\b | \bsshd\b", re.IGNORECASE | re.VERBOSE)

# Flags that consume a value, from `ssh -h` (OpenSSH 9.6: `-B bind_interface`
# and `-P tag` are in it and were missed once). The value may be the next
# token or attached to the letter, which is what makes an option cluster
# readable at all: in `-oLogLevel=ERROR` the `o` takes everything after it, so
# the `L` in `LogLevel` is part of a VALUE and not a forward.
_SSH_VALUE_FLAGS = set("BbcDEeFIiJLlmOoPpQRSWw")
_SSH_FORWARD_FLAGS = set("LRD")
_SSH_COMMAND = re.compile(r"\bssh\b", re.IGNORECASE)
# The same forwarding, configured instead of flagged: `-oLocalForward=…`,
# `-o DynamicForward=1080`, or a line in a config file. Attached to the `o`
# there is no word boundary in front of it, so the prose pattern cannot see it.
_FORWARD_DIRECTIVE = re.compile(r"(Local|Remote|Dynamic)Forward", re.IGNORECASE)


def _ssh_tokens(tail: str) -> list[str]:
    """Shell tokens, with concatenated quoting handled.

    `-oProxyCommand="ssh jump nc %h %p"` is ONE argument: the quote starts
    mid-token. POSIX mode joins adjacent quoted and unquoted segments, which
    non-POSIX mode does not - and getting that wrong made the walk mistake
    `jump` for the destination and miss the forward after it.
    """
    try:
        return shlex.split(tail, posix=True)
    except ValueError:
        # An unbalanced quote is not a command; fall back to a plain split
        # rather than dropping the line from the scan entirely.
        return tail.split()


def _ssh_option_flags(line: str) -> set[str]:
    """The option LETTERS that ssh itself is given on this line.

    `ssh [options] destination [command [argument ...]]`. The walk reads
    option tokens letter by letter and stops a token at the first
    value-taking letter, because everything after that letter is its value;
    it stops the whole section at the first token that is not an option and
    is not a value, because that is the destination and what follows runs on
    the far side.

    Returning LETTERS rather than text is what removes the last guess: inside
    ssh's own options, `-L`, `-R` and `-D` are forwarding flags whatever their
    argument looks like, so a socket-to-socket forward and a bare `-R 1080`
    need no shape rule at all.
    """
    flags: set[str] = set()
    for match in _SSH_COMMAND.finditer(line):
        pending_letter = ""
        for token in _ssh_tokens(line[match.end():]):
            if pending_letter:
                if pending_letter == "o" and _FORWARD_DIRECTIVE.search(token):
                    flags.add("L")
                pending_letter = ""
                continue
            if not token.startswith("-") or token == "-":
                break  # the destination
            for index, letter in enumerate(token[1:], start=1):
                if not letter.isalpha():
                    break
                flags.add(letter)
                if letter in _SSH_VALUE_FLAGS:
                    # The rest of this token, or the next one, is its value.
                    attached = token[index + 1:]
                    if attached:
                        # `-oLocalForward=…` is a forward that neither the
                        # letter walk nor the prose pattern can see: the
                        # directive is concatenated to the `o`, so there is no
                        # word boundary in front of it.
                        if letter == "o" and _FORWARD_DIRECTIVE.search(attached):
                            flags.add("L")
                    else:
                        pending_letter = letter
                    break
    return flags


def _forwarding_hit(line: str, *, strict: bool) -> bool:
    """Prose anywhere on the line; flags only in SSH's own option section."""
    if RECIPE_PROSE.search(line):
        return True
    if _SSH_COMMAND.search(line):
        if _ssh_option_flags(line) & _SSH_FORWARD_FLAGS:
            return True
    elif RECIPE_FLAGS.search(line):
        # A config-file forward has no `ssh` on the line at all.
        return True
    return bool(strict and CLIENT_SURFACE_ONLY.search(line))

# Which pattern applies where. Anything not listed gets the strict one - and
# deploy/docker-compose.yml deliberately stays strict: the revoked claim lived
# in a comment in that file, describing how the CLIENT reaches the service, so
# it is client surface for this purpose even though operators read it.
RECIPE_ONLY_PATHS = {
    "docs/deployment.md",
    "deploy/vps-update.sh",
    "deploy/entrypoint.sh",
}

# The one place the client's documentation may name the administration
# channel: a note that exists precisely to say it is NOT the client's path.
# Pinned verbatim, so widening it is an edit to this list and not a side
# effect of rewording a paragraph.
ALLOWED_OPERATIONS_NOTES: dict[str, tuple[str, ...]] = {
    "client/README.md": (
        "> Operations note: SSH is how an operator administers the server host. It is",
    ),
    # The runbook's own prohibition sentence: it names the thing in order to
    # forbid it. A gate that made this unsayable would push the next author
    # towards a vaguer warning. It is kept on ONE unwrapped line in the
    # document, so reflowing the paragraph around it cannot turn a pin into
    # what looks like a policy violation.
    "docs/deployment.md": (
        "Inventing one here (a forwarded port, an open port, a new route) is exactly the decision this project stopped making by default.",
    ),
}


def _is_generated(parent_parts: tuple[str, ...]) -> bool:
    """Whether a path sits under a build artefact or a virtual environment."""
    return any(
        part in EXCLUDED_DIR_NAMES or part.endswith(EXCLUDED_DIR_SUFFIXES)
        for part in parent_parts
    )


def _scanned_paths() -> list[Path]:
    paths: list[Path] = []
    for tree in SCANNED_TREES:
        for path in sorted(tree.rglob("*")):
            if not path.is_file() or path.suffix not in SCANNED_SUFFIXES:
                continue
            if _is_generated(path.relative_to(tree).parts[:-1]):
                continue
            paths.append(path)
    paths.extend(path for path in SCANNED_FILES if path.is_file())
    assert paths, "the scan found no files at all, which would pass vacuously"
    return paths


def _logical_lines(text: str) -> list[tuple[int, str]]:
    """(first line number, joined text) for every line, continuations merged.

    A shell command split over a backslash continuation - `ssh -N \\` on one
    line, `-L 8787:127.0.0.1:8787 <vps>` on the next - matches nothing when
    each physical line is examined alone, and would have walked straight
    through a per-line scan. The pieces are joined before matching, and the
    offence is reported at the line the command starts on.
    """
    joined: list[tuple[int, str]] = []
    pending_number: int | None = None
    pending_parts: list[str] = []
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.rstrip()
        start = pending_number if pending_number is not None else number
        if stripped.endswith("\\"):
            pending_parts.append(stripped[:-1].strip())
            pending_number = start
            continue
        pending_parts.append(stripped.strip() if pending_parts else line)
        joined.append((start, " ".join(part for part in pending_parts if part)))
        pending_parts = []
        pending_number = None
    if pending_parts:
        joined.append(
            (pending_number or len(text.splitlines()), " ".join(pending_parts))
        )
    return joined


def _offending_lines(relative: str, text: str) -> list[str]:
    """Every line carrying a forwarding token, minus the allowlisted ones."""
    allowed = ALLOWED_OPERATIONS_NOTES.get(relative, ())
    strict = relative not in RECIPE_ONLY_PATHS
    offences = []
    for number, line in _logical_lines(text):
        if not _forwarding_hit(line, strict=strict):
            continue
        if line.strip() in allowed:
            continue
        offences.append(f"{relative}:{number}: {line.strip()}")
    return offences


def test_the_shipped_client_surface_names_no_forwarding_path() -> None:
    """AC20. The client must not depend on, document, or advertise a
    host-administration channel as the way it reaches the service."""
    offences: list[str] = []
    for path in _scanned_paths():
        offences.extend(
            _offending_lines(
                path.relative_to(ROOT).as_posix(), path.read_text(encoding="utf-8")
            )
        )

    assert not offences, (
        "the client surface may not present a host-administration channel as "
        "its path to the service:\n" + "\n".join(offences)
    )


